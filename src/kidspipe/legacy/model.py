"""KiDS-Legacy COSEBIs forward model: physical parameters -> 126-vector E_n (21 pairs x modes 1-6).

Pipeline (mirrors Wright et al. 2025 Sect. 2, Appendix A/B):
  CAMB (linear + HMcode-2020 with baryon feedback log T_AGN, mnu=0.06 normal hierarchy, k <= kmax_h h/Mpc,
  log-log extension to 500 h/Mpc, 150-node z grid)  ->  Limber C_ell with n_i(z - bias_i) (cubic interpolation of the
  Z_MID-node n(z)), per-bin NLA amplitude A_i = a f_r,i (M_i/M_piv)^beta  ->  E_n = 1/2pi int dl l W_n(l) C(l)
  with COSEBIs filters regenerated by mpmath for theta in [2, 300] arcmin.
Parameter dict keys: omch2, ombh2, h0, n_s, A_s (or ln1e10As), log_t_agn, a, beta, log10_M_mean_1..6, bias_1..6.
"""
from __future__ import annotations

import threading
from collections import OrderedDict
from dataclasses import dataclass, field, replace

import numpy as np

from .._compat import trapezoid
from scipy.interpolate import CubicSpline

from ..theory.cosebis import CosebisFilters, cosebis_operator
from ..theory.limber import Limber
from ..theory.linear import Z_GRID_SPEC
from ..theory.nonlinear import extend_high_k
from .data import LegacyData, N_BIN, PAIRS
from .ia import F_RED, LOG10_M_PIV, ia_amplitudes

_PI = np.array([p[0] for p in PAIRS])
_PJ = np.array([p[1] for p in PAIRS])


@dataclass
class LegacyOptions:
    """Convention switches (defaults = best-evidence choices, see docs/interface_notes/legacy.md)."""
    tmin: float = 2.0
    tmax: float = 300.0
    n_modes: int = 6
    n_ell: int = 100                 # log nodes of the model C_ell grid
    ell_min: float = 1.0
    ell_max: float = 1.0e5
    lmax_int: float | None = 1.0e5   # upper l limit of the E_n integral (None: 1e4/theta_max)
    kmax_h: float = 10.0             # CosmoPower box: k <= 10 h/Mpc, extended log-log to 500 h/Mpc
    nk: int = 200
    minkh: float = 1.0e-4
    z_grid: np.ndarray = field(default_factory=lambda: Z_GRID_SPEC)
    n_nodes: int = 2000              # Limber z nodes
    dz_sign: int = +1                # n'(z) = n(z - dz_sign * bias)
    nz_interp: str = "cubic"         # 'cubic' | 'linear'
    clip_negative_nz: bool = False
    ia_mode: str = "massdep"         # 'massdep' | 'nla_global'
    mnu: float = 0.06
    hierarchy: str = "normal"
    feedback: bool = True            # mead2020_feedback (else mead2020, no baryons)
    f_r: np.ndarray = field(default_factory=lambda: F_RED.copy())
    log10_m_piv: float = LOG10_M_PIV
    n_amp_scale: float = 1.0         # test hook (multiplies IA amplitude)
    cut_neg_k: bool = False


class LegacyCosebisModel:
    def __init__(self, options: LegacyOptions | None = None, data: LegacyData | None = None, nthreads: int = 4,
                 cache_dir=None, cache_size: int = 3, filters=None):
        self.opt = options if options is not None else LegacyOptions()
        o = self.opt
        self.data = LegacyData.load() if data is None else data
        self.nthreads = nthreads
        self.z_nz = self.data.z_mid
        nz = np.clip(self.data.nz, 0, None)
        self.nz0 = nz / trapezoid(nz, self.z_nz, axis=-1)[:, None]
        self.ell = np.logspace(np.log10(o.ell_min), np.log10(o.ell_max), o.n_ell)
        self.filters = filters if filters is not None else CosebisFilters(o.tmin, o.tmax, o.n_modes, source="mpmath")
        self.M = cosebis_operator(self.ell, self.filters, o.n_modes, lmin=o.ell_min, lmax=o.lmax_int,
                                  nthreads=nthreads, cache_dir=cache_dir)
        self._lock = threading.RLock()
        self._cache: OrderedDict = OrderedDict()
        self._cache_size = cache_size
        self.last_derived: dict = {}
        self.cl_last = None

    # ------------------------------------------------------------------ cosmology stage
    def _cosmo(self, p):
        o = self.opt
        As = p["A_s"] if "A_s" in p else float(np.exp(p["ln1e10As"]) * 1e-10)
        key = tuple(float(p[k]) for k in ("omch2", "ombh2", "h0", "n_s", "log_t_agn")) + (float(As),)
        with self._lock:
            hit = self._cache.get(key)
            if hit is not None:
                self._cache.move_to_end(key)
                return hit
        import camb
        h = float(p["h0"])
        kw = dict(H0=100 * h, ombh2=float(p["ombh2"]), omch2=float(p["omch2"]), ns=float(p["n_s"]), As=float(As),
                  mnu=o.mnu, neutrino_hierarchy=o.hierarchy, omk=0, WantTransfer=True, kmax=20.0,
                  redshifts=list(np.asarray(o.z_grid)[::-1]))
        if o.feedback:
            kw.update(halofit_version="mead2020_feedback", HMCode_logT_AGN=float(p["log_t_agn"]))
        else:
            kw.update(halofit_version="mead2020")
        pars = camb.set_params(**kw)
        pars.Reion.Reionization = False
        pars.NonLinear = camb.model.NonLinear_pk
        res = camb.get_results(pars)
        kh, zz, pk = res.get_matter_power_spectrum(minkh=o.minkh, maxkh=o.kmax_h, npoints=o.nk)
        zc = np.linspace(0.0, 6.0, 6000)
        chi_h = res.comoving_radial_distance(zc) * h
        om = float(res.Params.omegam)
        k_ext, pk_ext = extend_high_k(kh, pk)
        lim = Limber(self.ell, fidelity="fast", n_nodes=o.n_nodes)
        lim.set_power(chi_h, zc, om, zz, k_ext, pk_ext)
        lim.set_nz_grid(self.z_nz)
        derived = {"sigma_8": float(res.get_sigma8_0()), "omega_m": om}
        out = (lim, derived)
        with self._lock:
            self._cache[key] = out
            while len(self._cache) > self._cache_size:
                self._cache.popitem(last=False)
        return out

    # ------------------------------------------------------------------ n(z) shift
    def shifted_nz(self, bias) -> np.ndarray:
        o = self.opt
        bias = np.asarray(bias, float)
        out = np.empty_like(self.nz0)
        z = self.z_nz
        for i in range(N_BIN):
            zq = z - o.dz_sign * bias[i]
            if o.nz_interp == "cubic":
                v = CubicSpline(z, self.nz0[i])(zq)          # not-a-knot cubic (scipy interp1d 'cubic' equivalent)
            else:
                v = np.interp(zq, z, self.nz0[i])
            v = np.where((zq >= z[0]) & (zq <= z[-1]), v, 0.0)
            if o.clip_negative_nz:
                v = np.clip(v, 0, None)
            out[i] = v / trapezoid(v, z)
        return out

    def amplitudes(self, p) -> np.ndarray:
        o = self.opt
        lm = [p[f"log10_M_mean_{i+1}"] for i in range(N_BIN)]
        if o.ia_mode == "massdep":
            A = ia_amplitudes(p["a"], p["beta"], lm, o.f_r, o.log10_m_piv)
        else:
            A = np.full(N_BIN, float(p["a"]))
        return A * o.n_amp_scale

    # ------------------------------------------------------------------ forward model
    def cl(self, p):
        lim, der = self._cosmo(p)
        self.last_derived = der
        nzs = self.shifted_nz([p[f"bias_{i+1}"] for i in range(N_BIN)])
        C = lim.cl(nzs, self.amplitudes(p), z_nz=self.z_nz)
        return self.ell, C

    def mu(self, p) -> np.ndarray:
        """E_n vector (21*n_modes,), pair-major (FITS order), mode fastest."""
        _, C = self.cl(p)
        return (C[_PJ, _PI] @ self.M.T).reshape(-1)

    __call__ = mu
